📜 **Контракт с Гитом**

Ринсвинд обнаружил в подвалах Башни странный артефакт — демона по имени Гит. Этот демон помнит каждое изменение каждого свитка и может путешествовать во времени. Но сначала нужно заключить с ним контракт — инициализировать репозиторий.

📖 **Что такое Git?**
• Система контроля версий — помнит всю историю изменений
• Работает локально (не нужен интернет для коммитов)
• Каждый файл имеет три состояния: **modified** → **staged** → **committed**

📖 **Инициализация**:
• `git init` — создать новый репозиторий в текущем каталоге (появится `.git/`)
• `.git/` — скрытый каталог со всей историей репозитория
• Никогда не удаляй `.git/` без крайней необходимости!

📖 **Клонирование**:
• `git clone <url>` — скачать существующий репозиторий
• Создаёт полную копию со всей историей
• Автоматически настраивает remote `origin`

📖 **Три области Git**:
1. **Рабочий каталог** — где ты редактируешь файлы
2. **Staging area (индекс)** — подготовленные к коммиту изменения (`git add`)
3. **Репозиторий** — сохранённые коммиты (`.git/`)

📂 Рабочий каталог: `~/.termtrainer/git_001`

📋 **Попробуй**:
1. Выполни `cd ~/.termtrainer/git_001 && git init`
2. Посмотри содержимое `.git/`: `ls -la .git/`
3. Проверь статус: `git status`

VALIDATION
#!/bin/bash
DIR="$HOME/.termtrainer/git_001"
score=0

if [ -d "$DIR/.git" ]; then
  echo "✓ Репозиторий инициализирован (.git существует)"
  score=$((score+1))
else
  echo "✗ Выполни git init в $DIR"
fi

if [ -f "$DIR/.git/HEAD" ]; then
  echo "✓ .git/HEAD на месте"
  score=$((score+1))
fi

[ $score -ge 1 ] && { echo "✓ ok: Контракт с Гитом заключён! (баллов: $score/2)"; exit 0; }
echo "✗ Нужно выполнить git init"
exit 1

