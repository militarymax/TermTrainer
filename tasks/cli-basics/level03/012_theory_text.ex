───────────────────────────────────────
🔹 ЗАКЛИНАНИЯ ОБРАБОТКИ ТЕКСТА
───────────────────────────────────────

⚡ cut -d',' -f2 <файл> — вырезать колонку из таблицы
   -d',' = разделитель запятая (delimiter)
   -f2   = второе поле (field)
   Пример: cut -d',' -f3 data.csv → только города

⚡ sort <файл> — отсортировать строки по алфавиту
   sort -n  → сортировать как числа (10 > 2, а не "10" < "2")
   sort -r  → в обратном порядке

⚡ uniq — оставить только уникальные строки
   ⚠️ ВАЖНО: uniq работает только на ОТСОРТИРОВАННЫХ данных!
   Сначала sort, потом uniq. Всегда.
   uniq -c → посчитать сколько раз каждая строка встречается

⚡ wc -l <файл> — посчитать строки (Word Count Lines)

⚡ head -5 / tail -3 — первые/последние N строк

⚡ awk '{print $2}' — вывести второе поле (по пробелам)
   awk — это целый язык программирования.
   Но пока тебе нужна только одна заклинательная формула:
   awk '{print $N}' — вывести N-е поле

───────────────────────────────────────
💡 МАГИЧЕСКИЕ ТРУБОПРОВОДЫ (PIPELINES)
───────────────────────────────────────

Символ | (pipe) передаёт вывод одной команды в другую:

  команда1 | команда2 | команда3

Это как цепочка магов, передающих друг другу свитки:
первый читает, второй фильтрует, третий записывает.

Примеры:
  cat data.csv | cut -d',' -f3 | sort | uniq
  → список уникальных городов

  grep "ERROR" server.log | wc -l
  → количество ошибок

  cat data.csv | tail -n +2 | wc -l
  → количество строк без заголовка (-n +2 = со второй строки)

