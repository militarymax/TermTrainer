🔹 ЗАКЛИНАНИЯ НАВИГАЦИИ
───────────────────────────────────────

⚡ pwd — Узнать, где ты находишься (Print Working Directory)
   Маги часто теряются. Это заклинание спасало жизнь Ринсвинду
   чаще, чем он готов признать.
   Пример: $ pwd → /home/rincewind

⚡ ls — Окинуть взглядом содержимое комнаты (LiSt)
   Флаги:
     ls -la    — подробный список + скрытые двери (начинаются с .)
                 В Незримом Университете много тайных комнат!
     ls -lh    — размеры в человекочитаемом виде (KB, MB)
                 Потому что «4096» — это не размер, это заклинание
     ls -R     — заглянуть во все подсобные помещения
     ls -t     — сортировать по свежести (новые свитки первыми)
     ls -S     — сортировать по размеру (толстые тома первыми)

⚡ cd <путь> — Телепортироваться в другую комнату (Change Directory)
   Специальные порталы:
     cd ~      — вернуться в свою башню (домой)
     cd ..     — подняться на этаж выше
     cd .      — остаться на месте (бесполезно, но работает)
     cd /      — Корень Мироздания (самый верх файловой системы)
     cd -      — вернуться туда, откуда пришёл

⚡ cat <файл> — Прочитать свиток целиком
   Для коротких записей. Если свиток длинный — используй
   less или head/tail, иначе магический текст уползёт за край.

⚡ head -5 <файл> — Первые 5 строк свитка
⚡ tail -5 <файл> — Последние 5 строк свитка
⚡ wc -l <файл>   — Посчитать строки (Weight & Count Lines)

⚡ tree — Увидеть всю структуру здания целиком
   Работает не везде. Как и большинство магии.

