⚡ touch <файл> — создать пустой свиток (или обновить его магическую ауру)
   Примеры:
     touch report.txt          → создать пустой свиток report.txt
     touch file1.txt file2.txt → создать два свитка разом!
                                 Эффективность — вот ключ к магии.

⚡ mkdir <имя> — создать новую комнату (MaKe DIRectory)
   Флаги:
     mkdir -p a/b/c    → создать целую лестницу комнат сразу!
                         Без -p придётся создавать по одной.
                         С -p магия делает всё сама. Как и должно быть.
     mkdir -v dir_name  → показать что создано (verbose)
                          Полезно, если ты забыл, что только что сделал.
                          Ринсвинд постоянно забывает.

⚡ echo "текст" > файл — записать заклинание в свиток
   Примеры:
     echo "Hello" > hello.txt       → записать (ПЕРЕЗАПИСАТЬ! Старое — в Бездну!)
     echo "World" >> hello.txt      → ДОБАВИТЬ строку в конец
                                      Два угла >> = «добавить», один > = «заменить»
                                      Перепутаешь — потеряешь данные.
                                      Как тот студент из Алхимии...
     echo -e "Line1\nLine2" > f.txt → многострочное заклинание (\n = перенос)

