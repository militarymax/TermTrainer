⚡ rm <файл> — уничтожить свиток НАВСЕГДА (ReMove)
   КОРЗИНЫ НЕТ. Это не Анк-Морпорк, тут мусорщики не ходят.

   Флаги:
     rm -r dir/      → уничтожить комнату со всем содержимым
                       Вместе с подвалами. Вместе с призраками в подвалах.
     rm -i file.txt  → спросить подтверждение (interactive)
                       Единственная защита от собственной глупости.
     rm -f file.txt  → уничтожить без вопросов (force)
                       Для тех, кто точно знает что делает.
                       Или думает, что знает.
     rm -rf dir/     → уничтожить всё без вопросов (ОЧЕНЬ ОПАСНО!)

   ⚠️ НИКОГДА не произноси: rm -rf /
   Это как сказать «Уничтожь всю вселенную».
   Октаво предостерегает. Октаво не шутит.

⚡ rmdir <dir> — уничтожить ПУСТУЮ комнату
   Если в комнате хоть один свиток — rmdir откажется.
   Это единственное безопасное заклинание удаления.
   Используй, пока можешь.

