🔹 КОПИРОВАНИЕ И ПЕРЕМЕЩЕНИЕ АРТЕФАКТОВ
───────────────────────────────────────

⚡ cp <откуда> <куда> — создать копию артефакта (CoPy)
   Флаги:
     cp -r dir/ backup/    → копировать комнату со всем содержимым
                             Без -r cp скажет: «Это папка, я так не умею.»
     cp -i file.txt copy/  → спросить перед перезаписью (interactive)
                             «Вы уверены?» — да, магия бывает вежливой.
     cp -v file.txt copy/  → показать что скопировано (verbose)
   Примеры:
     cp notes.txt archive/           → копия свитка в архиве
     cp notes.txt archive/notes.bak → копия с новым именем
     cp -r drafts/ backup/           → резервная копия всей черновой

⚡ mv <откуда> <куда> — переместить ИЛИ ПЕРЕИМЕНОВАТЬ (MoVe)
   ⚡ Важно: mv — это ОДНО заклинание, но ДВА эффекта!

   1. ПЕРЕМЕЩЕНИЕ: mv file.txt other_dir/
      Артефакт перемещён в другую комнату.
      На старом месте он исчезает!

   2. ПЕРЕИМЕНОВАНИЕ: mv old.txt new.txt
      Тот же артефакт, новое имя. Как титул мага —
      суть та же, звучит иначе.

   Разница? Всё зависит от того, КУДА указывает путь:
     mv draft1.txt final.txt        → переименование (та же комната)
     mv final.txt archive/          → перемещение (в другую комнату)
     mv final.txt archive/final.txt → перемещение с явным путём

   Флаги:
     mv -i old new  → спросить перед перезаписью
                      Потому что mv МОЛЧА затирает файлы с таким же именем.
                      Молча и безжалостно. Как Смерть. Но менее вежливо.
     mv -v old new  → показать что сделано

