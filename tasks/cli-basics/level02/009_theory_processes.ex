🔹 ОБНАРУЖЕНИЕ ПРИЗРАКОВ
───────────────────────────────────────

⚡ ps aux — список ВСЕХ призванных сущностей
   Как магический бестиарий. Показывает имя демона,
   его PID (инвентарный номер), сколько маны (CPU%)
   и памяти (MEM%) он пожирает.

   Колонки которые тебе нужны:
     USER   — кто призвал демона
     PID    — уникальный номер демона (как инвентарный номер)
     %CPU   — сколько маны жрёт
     %MEM   — сколько памяти оккупирует
     COMMAND — имя демона / заклинания

⚡ ps aux | grep <имя> — найти демона по имени
   Тысячи сущностей в системе. grep сужает поиск.
   Пример: ps aux | grep nginx → все демоны nginx

⚡ top — наблюдать за БИТВОЙ ДЕМОНОВ в реальном времени
   Как магический радар. Видно кто сколько жрёт,
   кто нападает на CPU, кто прячется в swap.
   q — выйти из top (иначе он будет показывать вечно)

⚡ jobs — твои ЛИЧНЫЕ фоновые задачи
   Только те демоны, которых ты призвал в ЭТОЙ сессии.

───────────────────────────────────────
🔹 ЗАПУСК ДЕМОНОВ В ФОНЕ
───────────────────────────────────────

⚡ command & — запустить заклинание В ФОНЕ
   Демон работает, а ты свободен.
   Примеры:
     sleep 100 &       → усыпить что-то на 100 секунд, не ждать
     ./long_script.sh & → запустить длинный ритуал и пойти пить чай

   Шелл скажет: [1] 12345
     [1]   — номер фоновой задачи
     12345 — PID (инвентарный номер демона)

⚡ nohup command & — запустить НЕУБИВАЕМОГО демона
   Обычно, если закрыть терминал, все демоны умирают.
   nohup делает демона бессмертным (по крайней мере,
   до перезагрузки системы).

───────────────────────────────────────
🔹 УСМИРЕНИЕ ДЕМОНОВ (kill)
───────────────────────────────────────

⚡ kill <PID> — вежливая просьба уйти (SIGTERM, сигнал 15)
   «Уважаемый демон, не могли бы вы завершить свою работу
   и покинуть этот мир? Спасибо.»
   Демон МОЖЕТ отказаться. Игнорировать. Убежать.

⚡ kill -9 <PID> — ПИНОК В БЕЗДНУ (SIGKILL)
   Демона не спрашивают. Демона уничтожают.
   Ядро ОС лично вышвыривает его из реальности.
   Используй ТОЛЬКО когда kill (без -9) не сработал.

⚡ killall <имя> — уничтожить ВСЕХ демонов с таким именем
   killall nginx → все демоны nginx умрут. Все разом.
   Удобно. Опасно. Как фаербол в библиотеке.

⚡ pkill <шаблон> — умный killall (по части имени)
   pkill -f "python.*server" → убить всех питон-серверов

💡 СИГНАЛЫ — КАК ЗАКЛИНАНИЯ ИЗГНАНИЯ:
   SIGTERM (15) — вежливая просьба уйти (kill PID)
   SIGKILL (9)  — пинок в астрал (kill -9 PID)
   SIGHUP (1)   — перезагрузка конфигурации (встряхнуть демона)
   SIGSTOP (19) — заморозить (демон застывает во льду)

   Полный список: kill -l (list — все доступные заклинания)

───────────────────────────────────────
🔹 ПЕРЕМЕЩЕНИЕ МЕЖДУ МИРАМИ
───────────────────────────────────────

⚡ fg — вытащить демона НА ПЕРЕДНИЙ ПЛАН (foreground)
   Если ты запустил что-то в фоне и хочешь
   посмотреть что оно делает — fg.

⚡ bg — отправить демона ОБРАТНО В ФОН (background)
   Если ты нажал Ctrl+Z (заморозил процесс),
   bg разморозит его, но в фоне.

⚡ Ctrl+Z — ЗАМОРОЗИТЬ текущий процесс
   Процесс останавливается и ждёт. Можно разморозить
   через fg (передний план) или bg (фон).

💡 ЖИЗНЕННЫЙ ЦИКЛ ДЕМОНА:
   Запуск (&) → работа → kill (SIGTERM) → «нет, не уйду!»
   → kill -9 (SIGKILL) → 💀

