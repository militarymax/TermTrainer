TASK
📓 **Лабораторный журнал**

Ты — алхимик. Нужно вести лабораторный журнал, собирая данные из разных источников и фильтруя ошибки.

ASSIGNMENT
📋 **Задания**:
1. Выведи содержимое `рецепт.txt` и **добавь** к нему строку `- Мед фей (опционально)` (сохрани в `рецепт_полный.txt`)
2. Создай файл `журнал.txt` с заголовком `=== Лабораторный журнал ===` (перезапись)
3. Добавь в `журнал.txt` текущую дату (подсказка: `date >> журнал.txt`)
4. Попробуй прочитать **несуществующий** файл `проклятая_книга.txt`. Перенаправь ошибку (stderr) в `ошибки.log`
5. Выведи содержимое `рецепт_полный.txt` и **подсчитай** количество строк в нём — одной командой (через конвейер `|`)
6. Эксперимент: направь и stdout, и stderr команды `ls несуществующий_каталог` в файл `полный_лог.txt`

📂 Рабочий каталог: `~/.termtrainer/textfu_004`

📂 Перейди в рабочий каталог: cd $HOME/.termtrainer/textfu_004

⚠ Напоминание:
• `>` — перезапись файла
• `>>` — добавление в конец
• `2>` — перенаправление stderr
• `2>&1` — stderr туда же, куда stdout

VALIDATION
#!/bin/bash
DIR="$HOME/.termtrainer/textfu_004"
score=0

if [ ! -f "$DIR/рецепт.txt" ]; then
  echo "✗ fail: рецепт.txt не найден"
  exit 1
fi

# Проверка 1: рецепт_полный.txt с дополненным ингредиентом
if [ -f "$DIR/рецепт_полный.txt" ]; then
  if grep -qi "Мед фей" "$DIR/рецепт_полный.txt" 2>/dev/null; then
    echo "✓ рецепт_полный.txt содержит новый ингредиент"
    score=$((score + 1))
  fi
fi

# Проверка 2: журнал.txt создан
if [ -f "$DIR/журнал.txt" ]; then
  echo "✓ журнал.txt создан"
  score=$((score + 1))
fi

# Проверка 3: ошибки.log существует
if [ -f "$DIR/ошибки.log" ]; then
  echo "✓ ошибки.log существует"
  score=$((score + 1))
fi

# Проверка 4: полный_лог.txt создан
if [ -f "$DIR/полный_лог.txt" ]; then
  echo "✓ полный_лог.txt создан (stdout+stderr вместе)"
  score=$((score + 1))
fi

echo "✓ ok: Лабораторный журнал оформлен (баллов: $score)"
exit 0

