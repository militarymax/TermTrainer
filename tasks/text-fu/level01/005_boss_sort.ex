TASK
🐉 **Сортировка проклятых свитков** (БОСС)

Библиотекарь принёс ящик с проклятыми свитками. Некоторые названия дублируются, некоторые — в разном регистре. Нужно навести идеальный порядок. Это твой первый экзамен по текстовой магии!

ASSIGNMENT
📋 **Боевые задания**:
1. Создай файл `чистый_архив.txt` — отсортируй `архив.txt`, **игнорируя регистр** (подсказка: `sort -f`). Убери дубликаты.
2. Создай `статистика_архива.txt` — подсчитай, сколько раз встречается каждый свиток (частотный анализ, по убыванию). Учти, что `uniq` требует сортировки!
3. Отсортируй `продажи.txt` **по второму столбцу (числа) по убыванию** — так ты узнаешь самые продаваемые свитки. Сохрани в `рейтинг_продаж.txt`
4. Выведи **первые 10** и **последние 10** строк `лог_продаж.txt` — собери тренды. Сохрани в `тренды.txt`
5. Создай итоговый `отчёт_босса.txt` со всей собранной статистикой

📂 Рабочий каталог: `~/.termtrainer/textfu_005`

📂 Перейди в рабочий каталог: cd $HOME/.termtrainer/textfu_005

⚡ Подсказки:
• `sort -f` — игнорировать регистр
• `sort -k2 -n` — сортировка по второму столбцу, числовая
• `sort -k2 -nr` — то же, но по убыванию

VALIDATION
#!/bin/bash
DIR="$HOME/.termtrainer/textfu_005"
score=0

if [ ! -f "$DIR/архив.txt" ]; then
  echo "✗ fail: архив.txt не найден"
  exit 1
fi

# 1. Чистый архив (отсортирован, без дубликатов, игнор регистра)
if [ -f "$DIR/чистый_архив.txt" ]; then
  count=$(wc -l < "$DIR/чистый_архив.txt" 2>/dev/null)
  if [ "$count" -le 10 ] 2>/dev/null; then
    echo "✓ чистый_архив.txt: $count уникальных свитков"
    score=$((score + 2))
  fi
fi

# 2. Статистика архива
if [ -f "$DIR/статистика_архива.txt" ]; then
  echo "✓ статистика_архива.txt создана"
  score=$((score + 1))
fi

# 3. Рейтинг продаж
if [ -f "$DIR/рейтинг_продаж.txt" ]; then
  echo "✓ рейтинг_продаж.txt создан"
  score=$((score + 1))
fi

# 4. Тренды
if [ -f "$DIR/тренды.txt" ]; then
  echo "✓ тренды.txt создан"
  score=$((score + 1))
fi

# 5. Итоговый отчёт
if [ -f "$DIR/отчёт_босса.txt" ]; then
  lines=$(wc -l < "$DIR/отчёт_босса.txt" 2>/dev/null)
  if [ "$lines" -ge 3 ] 2>/dev/null; then
    echo "✓ отчёт_босса.txt: $lines строк"
    score=$((score + 1))
  fi
fi

echo "✓ ok: БОСС пройден! (баллов: $score/6)"
exit 0

