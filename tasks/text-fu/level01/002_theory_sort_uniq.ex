#!/bin/bash
DIR="$HOME/.termtrainer/textfu_002"
errors=0

if [ ! -f "$DIR/инвентарь.txt" ]; then
  echo "✗ fail: инвентарь.txt не найден"
  exit 1
fi

# Проверка: файл отсортирован (проверяем наличие отсортированного файла)
if [ -f "$DIR/отсортировано.txt" ]; then
  first=$(head -1 "$DIR/отсортировано.txt" 2>/dev/null)
  last=$(tail -1 "$DIR/отсортировано.txt" 2>/dev/null)
  echo "✓ отсортировано.txt: '$first' ... '$last'"
fi

# Проверка: подсчёт уникальных
if [ -f "$DIR/статистика.txt" ]; then
  echo "✓ статистика.txt создан"
fi

echo "✓ ok: Инвентаризация проведена"
exit 0

