TASK
📊 **Инвентаризация архива**

Библиотекарь протягивает тебе список артефактов. Список в хаосе — дубликаты, беспорядок. Нужно навести порядок: отсортировать, подсчитать и найти самое важное.

Изучи команды:
• `sort файл` — сортировка строк по алфавиту
• `sort -n файл` — числовая сортировка
• `sort -r файл` — обратная сортировка
• `sort -u файл` — уникальные строки (без дубликатов)
• `uniq файл` — убрать повторяющиеся строки (только соседние!)
• `uniq -c файл` — подсчитать количество повторений
• `uniq -d файл` — показать только дубликаты
• `wc -l файл` — подсчитать строки
• `wc -w файл` — подсчитать слова
• `wc -c файл` — подсчитать байты
• `head -n N файл` — первые N строк
• `tail -n N файл` — последние N строк
• `tail -f файл` — следить за файлом в реальном времени

