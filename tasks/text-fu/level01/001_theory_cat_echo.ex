TASK
📜 **Голос Библиотекаря**

Библиотекарь Незримого Университета — орангутан, который не произносит ни слова. Но его послания всегда находят адресата. Он общается через свитки, символы и… терминал.

Твоя задача — освоить базовые инструменты чтения и записи, чтобы понимать безмолвные приказы Библиотекаря.

Изучи команды:
• `cat файл` — вывести содержимое файла
• `echo "текст"` — вывести текст в терминал
• `echo "текст" > файл` — записать текст в файл (перезапись)
• `echo "текст" >> файл` — добавить текст в конец файла
• `printf "шаблон\n"` — форматированный вывод (аналог echo, но точнее)
• `команда1 | команда2` — конвейер: вывод первой команды → ввод второй
• `команда 2> файл` — перенаправить stderr в файл
• `команда > файл 2>&1` — перенаправить и stdout, и stderr в файл

