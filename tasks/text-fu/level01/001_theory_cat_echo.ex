echo "текст" > файл — создаст или перезапишет файл
echo "текст" >> файл — добавит строку в конец
Попробуй: cat ~/.termtrainer/textfu_001/приветствие.txt
Затем: echo "Мой первый свиток" > ~/.termtrainer/textfu_001/мой_свиток.txt
