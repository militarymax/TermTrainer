#!/bin/bash
DIR="$HOME/.termtrainer/textfu_001"
errors=0

# Проверка 1: пользователь прочитал приветствие (файл существует)
if [ ! -f "$DIR/приветствие.txt" ]; then
  echo "✗ fail: приветствие.txt не найден в $DIR"
  exit 1
fi

# Проверка 2: создан новый файл с echo >
if [ ! -f "$DIR/мой_свиток.txt" ]; then
  echo "⚠ Пропущено: не найден мой_свиток.txt (доп. балл)"
else
  lines=$(wc -l < "$DIR/мой_свиток.txt" 2>/dev/null)
  if [ "$lines" -gt 0 ] 2>/dev/null; then
    echo "✓ мой_свиток.txt создан ($lines строк)"
  fi
fi

# Проверка 3: добавлена строка в заметки
checklist_lines=$(wc -l < "$DIR/черновики/заметки.txt" 2>/dev/null)
if [ "$checklist_lines" -gt 3 ] 2>/dev/null; then
  echo "✓ Заметки дополнены (было 3 строки, стало $checklist_lines)"
fi

echo "✓ ok: Архивы прочитаны, голос усвоен"
exit 0

HINTS
