VALIDATION
#!/bin/bash
DIR="$HOME/.termtrainer/textfu_013"
score=0

if [ ! -d "$DIR/свитки" ]; then
  echo "✗ fail: каталог свитки не найден"
  exit 1
fi

# 1. отчёт_xargs.txt
if [ -f "$DIR/отчёт_xargs.txt" ]; then
  echo "✓ отчёт_xargs.txt создан"
  score=$((score + 1))
fi

# 2. ошибочные_логи.txt
if [ -f "$DIR/ошибочные_логи.txt" ]; then
  echo "✓ ошибочные_логи.txt создан"
  score=$((score + 1))
fi

# 3. чистый_отчёт.txt
if [ -f "$DIR/чистый_отчёт.txt" ]; then
  echo "✓ чистый_отчёт.txt создан"
  score=$((score + 1))
fi

# 4. имена_обрезано.txt
if [ -f "$DIR/имена_обрезано.txt" ]; then
  echo "✓ имена_обрезано.txt создан"
  score=$((score + 1))
fi

# 5. без_пробелов.txt
if [ -f "$DIR/без_пробелов.txt" ]; then
  echo "✓ без_пробелов.txt создан"
  score=$((score + 1))
fi

echo "✓ ok: Массовая очистка завершена (баллов: $score/5)"
exit 0

HINTS
find + wc -l: find свитки/ -name '*.txt' -exec wc -l {} \; > отчёт_xargs.txt
grep -rl ОШИБКА: grep -rl 'ОШИБКА' логи/ > ошибочные_логи.txt
Общее число строк: find . -name '*.txt' -exec cat {} \; | wc -l > чистый_отчёт.txt
cut первые 10 символов: cut -c1-10 герои.tsv > имена_обрезано.txt
tr сжать пробелы: tr -s ' ' < с_пробелами.txt > без_пробелов.txt
Верхний регистр: cat архив/*.txt | tr '[:lower:]' '[:upper:]' > заглавный_архив.txt
Найти и удалить проклятые: grep -rl 'ПРОКЛЯТЫЙ' свитки/ | xargs rm (осторожно!)