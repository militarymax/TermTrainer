TASK
🧹 **Массовая очистка проклятий** — практика xargs/cut/tr

В Архивах Университета — массовое заражение. Проклятые свитки, ошибочные логи, дубликаты. Обычной магией не справиться — нужны пакетные операции.

📋 **Задания**:
1. Создай `отчёт_xargs.txt`: выведи **все** имена файлов в каталоге `свитки/`, а затем подсчитай строки в каждом из них — одной командой (`find ... -exec` или `ls | xargs wc -l`)
2. Найди **все файлы .log**, содержащие слово `ОШИБКА`, и выведи только их имена. Сохрани в `ошибочные_логи.txt`
3. Создай `чистый_отчёт.txt`: найди все .txt файлы, рекурсивно, и посчитай общее количество строк во всех них (сумма). Подсказка: `find | xargs wc -l` + grep total
4. Вырежи **первые 10 символов** каждой строки из `герои.tsv` с помощью `cut -c1-10` — сохрани в `имена_обрезано.txt`
5. Создай `без_пробелов.txt`: возьми `с_пробелами.txt` и сожми множественные пробелы в один (`tr -s ' '`)
6. Создай `заглавный_архив.txt`: рекурсивно собери содержимое всех .txt файлов из `архив/` и переведи в ВЕРХНИЙ РЕГИСТР
7. Найди все файлы, содержащие `ПРОКЛЯТЫЙ`, и удали их с помощью `xargs rm` (ОСТОРОЖНО! Сначала проверь без `rm`: `grep -rl ПРОКЛЯТЫЙ свитки/`)

