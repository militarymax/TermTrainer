TASK
🔧 **Инструменты архивариуса**

Ты уже знаешь sort, uniq, sed, awk. Теперь пришло время освоить дополнительные инструменты текстовой магии — cut, tr, xargs, paste, join.

• `cut -d':' -f1,3 файл` — вырезать столбцы 1 и 3 (разделитель `:`)
• `cut -c1-10 файл` — вырезать символы 1-10
• `tr 'a-z' 'A-Z' < файл` — заменить символы (нижний → верхний регистр)
• `tr -d '\r' < файл` — удалить символ (`\r` — carriage return)
• `tr -s ' ' < файл` — сжать повторяющиеся пробелы в один
• `paste файл1 файл2` — склеить строки двух файлов (как колонки)
• `join -t':' файл1 файл2` — объединить файлы по общему полю (аналог SQL JOIN)
• `xargs команда` — читает stdin и передаёт аргументы команде
• `команда | xargs -I{} другая_команда {}` — подстановка каждого элемента

ASSIGNMENT

📂 Рабочий каталог: `~/.termtrainer/textfu_011`

📂 Перейди в рабочий каталог: cd $HOME/.termtrainer/textfu_011

⚡ **Зачем нужен xargs**: некоторые команды (например, `rm`, `cp`, `kill`) не читают stdin. `xargs` преобразует stdin в аргументы. Без xargs: `echo "file.txt" | rm` — не сработает. С xargs: `echo "file.txt" | xargs rm` — удалит.

