=== БЛОК 1 ===
Сортировка по двум полям: sort -t':' -k3,3 -k5,5rn предметы.csv > полный_инвентарь.txt
Топ-5: sort -t':' -k5 -rn предметы.csv | head -6 > топ5_предметов.txt
Общая стоимость: awk -F':' 'NR>1 {sum += $5 * $6} END {print "Общая стоимость:", sum}' предметы.csv > общая_стоимость.txt
Статистика категорий: awk -F':' 'NR>1 {count[$3]++; cost[$3] += $5*$6} END {for (c in count) printf "%s: %d шт, %.0f монет\n", c, count[c], cost[c]}' предметы.csv > статистика_категорий.txt

=== БЛОК 2 ===
В верхний регистр: tr '[:lower:]' '[:upper:]' < грязный_инвентарь.txt
Убрать проклятия + дубликаты + сортировка: tr '[:lower:]' '[:upper:]' < грязный_инвентарь.txt | grep -v 'ПРОКЛЯТ' | sort -u > чистый_инвентарь.txt

=== БЛОК 3 ===
Только ERROR: grep 'ERROR' системный_лог.txt > критические_ошибки.txt
Таймлайн: cut -c2-20 системный_лог.txt > таймлайн.txt
Только INFO + нижний регистр: grep 'INFO' системный_лог.txt | tr '[:upper:]' '[:lower:]' > лог_без_ошибок.txt

=== БЛОК 4 ===
Сводка: find отчёты/ -name 'отчёт_*.txt' ! -name '*спам*' -exec awk -F': ' '/Успеваемость/ {print FILENAME, $2}' {} \; > сводка_студентов.txt
Должники: find отчёты/ -name 'отчёт_*.txt' ! -name '*спам*' -exec awk -F': ' '/^Задолженность/ && $2+0 > 0 {print FILENAME, $2}' {} \; > должники.txt
Удалить tmp: find логи/ -name '*.tmp' -delete

=== БЛОК 5 ===
Финальный отчёт: echo "=== ПОЛНЫЙ ИНВЕНТАРЬ ===" > UBERBOSS_ОТЧЁТ.txt && cat полный_инвентарь.txt >> UBERBOSS_ОТЧЁТ.txt && echo "=== КРИТИЧЕСКИЕ ОШИБКИ ===" >> UBERBOSS_ОТЧЁТ.txt && cat критические_ошибки.txt >> UBERBOSS_ОТЧЁТ.txt