#!/bin/bash
DIR="$HOME/.termtrainer/textfu_016"
score=0
max=12

if [ ! -d "$DIR/архив_1" ]; then
  echo "✗ fail: архивы не найдены"
  exit 1
fi

# БЛОК 1
for f in "полный_инвентарь.txt" "топ5_предметов.txt" "общая_стоимость.txt" "статистика_категорий.txt"; do
  [ -f "$DIR/$f" ] && { echo "✓ $f"; score=$((score + 1)); }
done

# БЛОК 2
[ -f "$DIR/чистый_инвентарь.txt" ] && { 
  if ! grep -qi "ПРОКЛЯТ" "$DIR/чистый_инвентарь.txt" 2>/dev/null; then
    echo "✓ чистый_инвентарь.txt (без проклятий)"
    score=$((score + 1))
  fi
}

# БЛОК 3
for f in "критические_ошибки.txt" "таймлайн.txt" "лог_без_ошибок.txt"; do
  [ -f "$DIR/$f" ] && { echo "✓ $f"; score=$((score + 1)); }
done

# БЛОК 4
for f in "сводка_студентов.txt" "должники.txt"; do
  [ -f "$DIR/$f" ] && { echo "✓ $f"; score=$((score + 1)); }
done

# Очистка tmp
remaining=$(find "$DIR/логи/" -name '*.tmp' 2>/dev/null | wc -l)
if [ "$remaining" -eq 0 ] 2>/dev/null; then
  echo "✓ .tmp файлы удалены"
  score=$((score + 1))
fi

# Финальный отчёт
[ -f "$DIR/UBERBOSS_ОТЧЁТ.txt" ] && {
  lines=$(wc -l < "$DIR/UBERBOSS_ОТЧЁТ.txt" 2>/dev/null)
  [ "$lines" -ge 10 ] 2>/dev/null && { echo "✓ UBERBOSS_ОТЧЁТ.txt ($lines строк)"; score=$((score + 1)); }
}

echo "✓ ok: UBERBOSS пройден! (баллов: $score/$max)"
exit 0

