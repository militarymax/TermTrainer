TASK
👑 **Генеральная инвентаризация Незримого Университета** (UBERBOSS)

Архиканцлер лично явился в Архивы. Он требует полный, кристально чистый отчёт по всему Университету. Три Архива заражены хаосом: дубликаты, ошибки, спам, проклятые артефакты, временные файлы.

Это твой финальный экзамен. Примени ВСЕ навыки текстовой магии.

📋 **Задания**:

**БЛОК 1 — Инвентаризация (sort, uniq, awk)**:
1. Создай `полный_инвентарь.txt`: отсортируй `предметы.csv` по Категории, затем по Цене (убывание)
2. Создай `топ5_предметов.txt`: топ-5 предметов по Цене
3. Создай `общая_стоимость.txt`: посчитай общую стоимость ВСЕХ предметов (Цена × Количество) — одним awk
4. Создай `статистика_категорий.txt`: сколько предметов в каждой Категории и их суммарная стоимость

**БЛОК 2 — Очистка (sed, tr, sort -f)**:
5. Создай `чистый_инвентарь.txt`: из `грязный_инвентарь.txt`:
   a. Приведи к единому регистру (все заглавные или все строчные)
   b. Убери строки с ПРОКЛЯТ (удали проклятые артефакты)
   c. Убери дубликаты
   d. Отсортируй по алфавиту

**БЛОК 3 — Логи (grep, cut, sed)**:
6. Создай `критические_ошибки.txt`: строки только с ERROR из `системный_лог.txt`
7. Создай `таймлайн.txt`: вырежи только дату и время из ВСЕХ строк лога
8. Создай `лог_без_ошибок.txt`: удали ERROR и WARNING, оставь только INFO и приведи к нижнему регистру

**БЛОК 4 — Отчёты студентов (find, xargs, awk)**:
9. Создай `сводка_студентов.txt`: найди все `отчёт_*.txt` (кроме спама), для каждого выведи имя файла и значение Успеваемости
10. Создай `должники.txt`: найди студентов с Задолженность > 0 и выведи Имя и Долг
11. Найди и удали все `.tmp` файлы в `логи/` с помощью `find ... -delete`

**БЛОК 5 — Финальный отчёт**:
12. Создай `UBERBOSS_ОТЧЁТ.txt` — объедини ВСЕ созданные файлы с заголовками секций

