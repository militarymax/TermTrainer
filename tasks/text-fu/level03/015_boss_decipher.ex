#!/bin/bash
DIR="$HOME/.termtrainer/textfu_015"
score=0

if [ ! -d "$DIR/секция_А" ]; then
  echo "✗ fail: секция_А не найдена"
  exit 1
fi

# Инвентарь
for f in "отчёт_инвентарь.txt" "топ3_ценных.txt" "статистика_типов.txt" "обычные_предметы.txt"; do
  if [ -f "$DIR/$f" ]; then
    echo "✓ $f"
    score=$((score + 1))
  fi
done

# Логи
for f in "только_проклятия.txt" "лог_без_проклятий.txt" "время_ошибок.txt"; do
  if [ -f "$DIR/$f" ]; then
    echo "✓ $f"
    score=$((score + 1))
  fi
done

# Письма
for f in "важные_письма.txt" "отправители.txt"; do
  if [ -f "$DIR/$f" ]; then
    echo "✓ $f"
    score=$((score + 1))
  fi
done

# Финальный отчёт
if [ -f "$DIR/BOSS_ОТЧЁТ.txt" ]; then
  lines=$(wc -l < "$DIR/BOSS_ОТЧЁТ.txt" 2>/dev/null)
  if [ "$lines" -ge 5 ] 2>/dev/null; then
    echo "✓ BOSS_ОТЧЁТ.txt: $lines строк"
    score=$((score + 2))
  fi
fi

echo "✓ ok: БОСС дешифратора пройден! (баллов: $score/11)"
exit 0

HINTS
Сортировка по двум полям: sort -t':' -k3,3 -k5,5rn инвентарь.txt > отчёт_инвентарь.txt
Топ-3 по цене: sort -t':' -k5 -rn инвентарь.txt | head -4 > топ3_ценных.txt (head -4 включает заголовок)
Статистика типов: awk -F':' 'NR>1 {types[$3]++} END {for (t in types) print types[t], t}' инвентарь.txt > статистика_типов.txt
Обычные предметы: awk -F':' '$4 == "Обычный"' инвентарь.txt > обычные_предметы.txt
Проклятия: grep -E 'ERROR|ПРОКЛЯТ' лог_магия.txt > только_проклятия.txt
Без ошибок: grep -vE 'ERROR|WARNING' лог_магия.txt > лог_без_проклятий.txt
Время ошибок: grep 'ERROR' лог_магия.txt | cut -c2-20 > время_ошибок.txt
Важные письма: grep -vE 'spam|P\.S\.|!!!' письма.txt > важные_письма.txt
Отправители: grep -E '^От: ' письма.txt | cut -d' ' -f2 > отправители.txt
Финальный отчёт: cat отчёт_инвентарь.txt > BOSS_ОТЧЁТ.txt && echo "===" >> BOSS_ОТЧЁТ.txt && cat только_проклятия.txt >> BOSS_ОТЧЁТ.txt