✂️ **Искусство подмены — sed**

Библиотекарь выдал тебе гримуар с заклинаниями, но половина текста проклята: неправильные слова, лишние строки, устаревшие названия. Нужен sed — потоковый редактор, который может менять текст на лету, не открывая файл.

`s/что/на_что/` — замена (substitute). Первое вхождение в каждой строке.
`s/что/на_что/g` — замена **всех** вхождений в строке (global).

Основные команды sed:
• `sed 's/старое/новое/' файл` — заменить первое вхождение в каждой строке
• `sed 's/старое/новое/g' файл` — заменить все вхождения
• `sed 's/старое/новое/i' файл` — игнорировать регистр при замене
• `sed '/паттерн/d' файл` — удалить строки, содержащие паттерн
• `sed -n '2,4p' файл` — вывести строки 2-4
• `sed 's/^/ПРЕФИКС: /' файл` — добавить в начало строки
• `sed 's/$/:СУФФИКС/' файл` — добавить в конец строки
• `sed -i '' 's/старое/новое/g' файл` — замена НА МЕСТЕ (осторожно! macOS требует `-i ''`)

