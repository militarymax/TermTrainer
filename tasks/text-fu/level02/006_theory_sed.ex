#!/bin/bash
DIR="$HOME/.termtrainer/textfu_006"
score=0

if [ ! -f "$DIR/заклинание.txt" ]; then
  echo "✗ fail: заклинание.txt не найден"
  exit 1
fi

# Проверка: создан файл с исправлениями
if [ -f "$DIR/заклинание_v2.txt" ]; then
  echo "✓ заклинание_v2.txt создан"
  score=$((score + 2))
fi

if [ -f "$DIR/чистый_список.txt" ]; then
  echo "✓ чистый_список.txt создан"
  score=$((score + 1))
fi

echo "✓ ok: sed освоен (баллов: $score)"
exit 0

