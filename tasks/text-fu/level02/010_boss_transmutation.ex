#!/bin/bash
DIR="$HOME/.ninja_trainer/textfu_010"
score=0

if [ ! -f "$DIR/эксперименты.csv" ]; then
  echo "✗ fail: эксперименты.csv не найден"
  exit 1
fi

# 1. Только успехи
if [ -f "$DIR/только_успехи.csv" ]; then
  lines=$(wc -l < "$DIR/только_успехи.csv" 2>/dev/null)
  if ! grep -q "Провал" "$DIR/только_успехи.csv" 2>/dev/null; then
    echo "✓ только_успехи.csv: $lines строк (без провалов)"
    score=$((score + 2))
  fi
fi

# 2. Топ-5
if [ -f "$DIR/топ5_мощность.csv" ]; then
  lines=$(wc -l < "$DIR/топ5_мощность.csv" 2>/dev/null)
  if [ "$lines" -le 6 ] 2>/dev/null; then
    echo "✓ топ5_мощность.csv: $lines строк"
    score=$((score + 1))
  fi
fi

# 3. Статистика по стихиям
if [ -f "$DIR/стихии.txt" ]; then
  echo "✓ стихии.txt создан"
  score=$((score + 1))
fi

# 4. Средняя мощность
if [ -f "$DIR/средняя_мощность.txt" ]; then
  echo "✓ средняя_мощность.txt создана"
  score=$((score + 1))
fi

# 5. Заполненный отчёт
if [ -f "$DIR/отчёт_алхимика.txt" ]; then
  if ! grep -qi "НЕИЗВЕСТНО" "$DIR/отчёт_алхимика.txt" 2>/dev/null; then
    echo "✓ отчёт_алхимика.txt: заполнен данными"
    score=$((score + 1))
  fi
fi

# 6. Чистый отчёт (без разделителей)
if [ -f "$DIR/чистый_отчёт.txt" ]; then
  if ! grep -q "===" "$DIR/чистый_отчёт.txt" 2>/dev/null; then
    echo "✓ чистый_отчёт.txt: без разделителей"
    score=$((score + 1))
  fi
fi

echo "✓ ok: БОСС трансмутации пройден! (баллов: $score/7)"
exit 0

HINTS
Только успехи: awk -F',' '$4 == "Успех"' эксперименты.csv > только_успехи.csv
Топ-5 по мощности: sort -t',' -k5 -nr эксперименты.csv | head -6 > топ5_мощность.csv (head -6 включает заголовок)
Стихии (подсчёт): awk -F',' 'NR>1 {elem[$6]++} END {for (e in elem) print elem[e], e}' эксперименты.csv > стихии.txt
Средняя мощность по стихии: awk -F',' 'NR>1 {sum[$6] += $5; count[$6]++} END {for (e in sum) printf "%s: %.1f\n", e, sum[e]/count[e]}' эксперименты.csv > средняя_мощность.txt
Заполнить отчёт (sed): sed "s/СЕГОДНЯ/$(date +%Y-%m-%d)/" отчёт_алхимика.txt | sed 's/НЕИЗВЕСТНО/[посчитай]/g'
Удалить разделители: sed '/^===\|^---/d' отчёт_алхимика.txt > чистый_отчёт.txt