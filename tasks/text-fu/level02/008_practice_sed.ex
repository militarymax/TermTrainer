TASK
📜 **Проклятый гримуар** — практика sed

Гримуар заражён тёмной магией. Нужно очистить его с помощью sed.

ASSIGNMENT
📋 **Задания**:
1. Создай `гримуар_v2.txt`: замени **все** `v1.0`, `v2.0`, `v3.0` на `v4.0` (подсказка: `sed 's/v[0-9]\.[0-9]/v4.0/g'`)
2. Создай `гримуар_очищенный.txt`: удали **все строки**, содержащие слово `ТЁМНЫХ` (заголовки гримуаров)
3. Создай `гримуар_без_концовок.txt`: удали строки с `# КОНЕЦ ЗАКЛИНАНИЯ`
4. Создай `письмо_вежливое.txt`: замени `Декан` на `Уважаемый Декан` во всём файле
5. Создай `письмо_без_постскриптумов.txt`: удали **все строки**, начинающиеся с `P.S.` или `P.P.S.`
6. Создай `чистые_слова.txt`: удали строки, содержащие `ПРОКЛЯТОЕ`
7. В файле `гримуар.txt` замени **на месте** (`sed -i ''`) `КРАСНЫЙ` на `АЛЫЙ`

📂 Рабочий каталог: `~/.termtrainer/textfu_008`

⚠ macOS: `sed -i '' 's/old/new/g' file`

VALIDATION
#!/bin/bash
DIR="$HOME/.termtrainer/textfu_008"
score=0

if [ ! -f "$DIR/гримуар.txt" ]; then
  echo "✗ fail: гримуар.txt не найден"
  exit 1
fi

# 1. Версии заменены
if [ -f "$DIR/гримуар_v2.txt" ]; then
  if grep -q "v4.0" "$DIR/гримуар_v2.txt" 2>/dev/null; then
    echo "✓ гримуар_v2.txt: версии обновлены до v4.0"
    score=$((score + 1))
  fi
fi

# 2. Очищенный (без ТЁМНЫХ)
if [ -f "$DIR/гримуар_очищенный.txt" ]; then
  if ! grep -q "ТЁМНЫХ" "$DIR/гримуар_очищенный.txt" 2>/dev/null; then
    echo "✓ гримуар_очищенный.txt: тёмные заголовки удалены"
    score=$((score + 1))
  fi
fi

# 6. Чистые слова
if [ -f "$DIR/чистые_слова.txt" ]; then
  if ! grep -qi "проклятое" "$DIR/чистые_слова.txt" 2>/dev/null; then
    echo "✓ чистые_слова.txt: проклятые строки удалены"
    score=$((score + 1))
  fi
fi

# 7. Замена на месте
if grep -q "АЛЫЙ" "$DIR/гримуар.txt" 2>/dev/null; then
  echo "✓ гримуар.txt: КРАСНЫЙ → АЛЫЙ (на месте)"
  score=$((score + 1))
fi

echo "✓ ok: sed на практике (баллов: $score/4)"
exit 0

