💰 **Бухгалтерия Гильдии** — практика awk

Казначей Гильдии Магов уронил кипу счетов в котёл с зельем. Теперь данные в CSV, и их нужно обработать с помощью awk.

📋 **Задания**:
1. Выведи список **уникальных городов** из `продажи.csv` (3-й столбец с разделителем `,`)
2. Подсчитай **общую сумму продаж** (Количество × Цена) — создай `общая_выручка.txt`
3. Найди **самый продаваемый товар** по сумме количества — создай `топ_товар.txt`
4. Выведи только **имя и баллы** студентов (столбцы 1 и 3, разделитель `:`) — сохрани в `рейтинг.txt`
5. Найди **средний балл** по каждому курсу — создай `средний_балл.txt`
6. Выведи всех студентов с баллами **> 80** — создай `отличники.txt`
7. Подсчитай, сколько студентов живёт в каждом общежитии — создай `общежития.txt`

📂 Рабочий каталог: `~/.termtrainer/textfu_009`

⚡ Ключевые подсказки awk:
• `awk -F','` — разделитель запятая
• `awk -F':'` — разделитель двоеточие
• `$3` — третий столбец
• `sum += $3 * $4` — накопительная сумма
• `END {print sum}` — вывод после обработки

