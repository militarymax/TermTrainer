📊 **Магия столбцов — awk**

`sed` меняет текст построчно. Но что если нужно работать с **колонками данных** — как в таблице? Тут в игру вступает `awk` — мощный инструмент для обработки структурированного текста.

Основы awk:
• `awk '{print $1}' файл` — вывести первый столбец
• `awk '{print $1, $3}' файл` — вывести 1-й и 3-й столбцы
• `awk -F':' '{print $1}' файл` — использовать `:` как разделитель (по умолчанию пробел/таб)
• `awk '$3 > 50' файл` — вывести строки, где 3-й столбец > 50
• `awk '$2 == "Огонь"' файл` — строки, где 2-й столбец равен "Огонь"
• `awk '{sum += $3} END {print sum}' файл` — сумма 3-го столбца
• `awk 'NR==1{print; next} {print $0, $3*2}' файл` — вывести заголовок, потом строки с удвоенным 3-м столбцом
• `awk '{print NR, $0}' файл` — вывести с номерами строк (NR — номер записи)

📂 Рабочий каталог: `~/.ninja_trainer/textfu_007`

⚡ **Ключевые переменные awk**:
• `$1, $2, ... $NF` — столбцы
• `NR` — номер строки (Number of Record)
• `NF` — количество столбцов (Number of Fields)
• `BEGIN { }` — выполнить до чтения файла
• `END { }` — выполнить после чтения файла

