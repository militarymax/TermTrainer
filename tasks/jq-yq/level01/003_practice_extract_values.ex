#!/bin/bash
DIR="$HOME/.termtrainer/jqyq_003"
rm -rf "$DIR" 2>/dev/null
mkdir -p "$DIR"
cat > "$DIR/registry.json" << 'EOF'
{
  "отдел": "Казначейство",
  "год": 2024,
  "зелья": [
    {"id": 1, "название": "невидимость", "цена": 100, "склад": 15},
    {"id": 2, "название": "сила", "цена": 150, "склад": 0},
    {"id": 3, "название": "мудрость", "цена": 200, "склад": 8},
    {"id": 4, "название": "полёт", "цена": 300, "склад": 3}
  ],
  "поставщик": {
    "имя": "Зельеварение Морпурго",
    "город": "Анк-Морпорк"
  }
}
EOF

TASK
⚗️ **Реестр зелий**

Казначей поручил Ринсвинду составить отчёт из реестра. Нужно извлечь конкретные значения и построить новый объект.

ASSIGNMENT
📋 **Задания**:
1. Извлеки отдел: `jq '.отдел' registry.json`
2. Извлеки без кавычек: `jq -r '.отдел' registry.json`
3. Первый элемент массива: `jq '.зелья[0]' registry.json`
4. Название первого зелья: `jq -r '.зелья[0].название' registry.json`
5. Город поставщика через pipe: `jq -r '.поставщик | .город' registry.json`
6. Построй новый объект: `jq '{отдел, год, поставщик: .поставщик.имя}' registry.json`
7. Все названия зелий: `jq -r '.зелья[] | .название' registry.json`

📂 Рабочий каталог: `~/.termtrainer/jqyq_003`

VALIDATION
#!/bin/bash
DIR="$HOME/.termtrainer/jqyq_003"
score=0

result1=$(jq -r '.отдел' "$DIR/registry.json" 2>/dev/null)
[ "$result1" = "Казначейство" ] && { echo "✓ Отдел извлечён"; score=$((score+1)); }

result2=$(jq -r '.зелья[0].название' "$DIR/registry.json" 2>/dev/null)
[ "$result2" = "невидимость" ] && { echo "✓ Первое зелье найдено"; score=$((score+1)); }

result3=$(jq -r '.поставщик.город' "$DIR/registry.json" 2>/dev/null)
[ "$result3" = "Анк-Морпорк" ] && { echo "✓ Город поставщика"; score=$((score+1)); }

[ $score -ge 2 ] && { echo "✓ ok: Реестр освоен! (баллов: $score/3)"; exit 0; }
echo "✗ Нужно больше практики (баллов: $score/3)"
exit 1

HINTS
Поле: jq '.ключ' файл
Без кавычек: jq -r '.ключ' файл
Вложенное поле: jq '.a.b.c' файл или jq '.a | .b | .c' файл
Элемент массива: jq '.массив[0]' файл — первый элемент
Все элементы: jq '.массив[]' файл — развернуть массив
Построить объект: jq '{новый_ключ: .старый.путь}' файл
