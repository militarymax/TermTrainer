HINTS
Map: jq '.массив | map(.поле)' файл — применить к каждому элементу
Select: jq '.массив[] | select(.поле > значение)' файл — фильтр по условию
Отличники в массиве: jq '[.items[] | select(.score > 80)]' файл — обернуть в []
Length: jq '.array | length' файл — количество элементов
Has: jq '.[] | has("email")' файл — проверить наличие ключа
Del: jq '.[] | del(.ненужное)' файл — удалить поле
