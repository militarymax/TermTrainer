TASK
📜 **Фильтры и карты Астролога**

Астрологу нужно не просто читать данные, но и фильтровать их — находить лучших студентов, считать средние оценки, проверять наличие полей.

📖 **map** — применить функцию к каждому элементу:
• `jq '.студенты | map(.имя)' файл` → массив имён
• `jq '.студенты | map(.оценка)' файл` → массив оценок

📖 **select** — фильтрация по условию:
• `jq '.студенты[] | select(.оценка > 80)' файл` — только отличники
• `jq '.студенты[] | select(.факультет == "магия")' файл` — только маги

📖 **Утилиты**:
• `length` — длина массива или строки
• `has("ключ")` — есть ли ключ в объекте
• `del(.ключ)` — удалить ключ из объекта
• Математика: `+`, `-`, `*`, `/`, `%`

📖 **Примеры**:
```bash
jq '.студенты | map(.оценка) | add' students.json     # сумма оценок
jq '[.студенты[] | select(.оценка > 80)]' students.json # отличники как массив
jq '.студенты | length' students.json                    # количество
jq '.студенты[] | del(.факультет)' students.json         # без факультета
```

