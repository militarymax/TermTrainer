📜 СВИТОК ЗНАНИЙ #007: Кодекс Астролога

Главный Астролог Университета поднялся на башню и произнёс:
«Звёзды не прощают ошибок. Одна неэкранированная переменная —
и всё заклинание рушится, унося за собой пол-Башни.
Мы уже трижды перестраивали восточное крыло.
Позорище. Научитесь писать НАДЁЖНЫЕ заклинания.»

───────────────────────────────────────
🔹 СВЯЩЕННАЯ ТРОИЦА: set -euo pipefail
───────────────────────────────────────

Каждый скрипт должен начинаться так:

```bash
#!/bin/bash
set -euo pipefail
```

• `set -e` — НЕМЕДЛЕННО выйти при ошибке любой команды.
  Без этого скрипт продолжит работать даже если всё горит!
  
• `set -u` — ошибка при использовании НЕОПРЕДЕЛЁННОЙ переменной.
  Опечатка в `$nam` вместо `$name` → скрипт упадёт, а не промолчит.

• `set -o pipefail` — ошибка в ЛЮБОЙ части конвейера = ошибка конвейера.
  Без этого: `false | true` → успех (код 0)! Это опасно!

───────────────────────────────────────
🔹 КАВЫЧКИ — ЗАКОН АСТРОЛОГА
───────────────────────────────────────

⚠️ ВСЕГДА оборачивай переменные в двойные кавычки:

```bash
# ПЛОХО:
echo $name          # Пробелы разорвут аргументы!
rm $dir/*           # Если $dir пуст → rm /* (УДАЛИТ ВСЁ!)

# ХОРОШО:
echo "$name"        # Безопасно даже с пробелами
rm "$dir"/*         # Если $dir пуст → ошибка, а не катастрофа
```

• `"$@"` — каждый аргумент отдельно (ПРАВИЛЬНО)
• `$@` или `$*` — без кавычек — разбиение на слова (ОПАСНО)

───────────────────────────────────────
🔹 [[ ]] ВМЕСТО [ ]
───────────────────────────────────────

```bash
# Старый путь (опасен):
[ "$name" = "Rincewind" ]    # Пустая переменная = синтаксическая ошибка!

# Новый путь (безопасен):
[[ "$name" == "Rincewind" ]] # Работает даже с пустыми переменными
```

Преимущества `[[ ]]`:
• Нет проблем с пустыми переменными
• `&&`, `||`, `<`, `>` без экранирования
• Поддержка `=~` для regex

───────────────────────────────────────
🔹 ФУНКЦИИ — РИТУАЛЫ
───────────────────────────────────────

```bash
brew_potion() {
    local name="$1"        # local — переменная только внутри функции!
    local power="$2"
    printf "Brewing %s (power: %d)\n" "$name" "$power"
}

brew_potion "healing" 50   # → Brewing healing (power: 50)
```

• `local var` — переменная существует ТОЛЬКО внутри функции
• Без `local` — переменная ГЛОБАЛЬНАЯ (меняет внешний мир!)
• `return N` — вернуть код (0-255), НЕ строку
• Для возврата строки — `echo` + захват: `result=$(my_func)`

