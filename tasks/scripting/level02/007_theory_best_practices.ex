🔹 TRAP — ЛОВУШКА ДЛЯ ДЕМОНОВ
───────────────────────────────────────

```bash
cleanup() {
    rm -f "$tempfile"
    echo "Cleanup complete!"
}

ASSIGNMENT
trap cleanup EXIT    # Выполнится при ЛЮБОМ выходе из скрипта
```

• `trap cmd EXIT` — при завершении скрипта (любом!)
• `trap cmd INT` — при Ctrl+C
• `trap cmd TERM` — при сигнале terminate
• Используй для удаления временных файлов!

