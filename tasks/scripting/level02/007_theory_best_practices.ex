HINTS
set -e: выход при ошибке — без этого скрипт продолжает после ошибки!
set -u: ошибка при неопределённой переменной — ловит опечатки
set -o pipefail: ошибка в любой части пайпа = ошибка всего пайпа
Святая троица: set -euo pipefail — ставь в начало КАЖДОГО скрипта
Кавычки: ВСЕГДА "$var" — пробелы и пустые значения без кавычек = беда
"$@": безопасный перебор аргументов, $@ без кавычек — опасно
[[ ]]: безопаснее [ ], поддерживает regex через =~, нет проблем с пустыми vars
local: local var внутри функции — иначе переменная глобальная!
trap cleanup EXIT: гарантированная очистка при любом выходе
