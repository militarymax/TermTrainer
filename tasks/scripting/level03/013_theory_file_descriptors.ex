echo text >&3: записать в дескриптор 3
exec 4<file: открыть дескриптор 4 для чтения
read line <&4: прочитать из дескриптора 4
exec 3>&-: закрыть дескриптор 3
cmd &: запустить команду в фоне
wait: дождаться всех фоновых задач
$!: PID последней фоновой команды
mkfifo + exec: именованный канал для ограниченного параллелизма
