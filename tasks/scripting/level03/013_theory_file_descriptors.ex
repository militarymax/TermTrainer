───────────────────────────────────────
🔹 ФАЙЛОВЫЕ ДЕСКРИПТОРЫ И exec
───────────────────────────────────────

```bash
# Создать свой дескриптор для записи:
exec 3>"$DIR/tower_log.txt"
echo "Spell cast!" >&3          # Записать в дескриптор 3
echo "Another spell!" >&3

# Читать из дескриптора:
exec 4<"$DIR/tower_log.txt"
read -r line <&4                # Прочитать строку из дескриптора 4
echo "Read: $line"

# Закрыть дескрипторы:
exec 3>&-                       # Закрыть на запись
exec 4<&-                       # Закрыть на чтение

# Чтение+запись одновременно:
exec 5<>"$DIR/two_way.txt"
echo "data" >&5
read -r back <&5
```

───────────────────────────────────────
🔹 ПАРАЛЛЕЛЬНЫЕ РИТУАЛЫ (ФОНОВЫЕ ЗАДАЧИ)
───────────────────────────────────────

```bash
# Запустить в фоне:
slow_spell() { sleep 2; echo "Potion ready!"; }
slow_spell &                    # & = запустить в фоне
echo "Doing other things..."    # Выполнится сразу!
wait                             # Дождаться фоновой задачи
echo "All done!"
```

• `cmd &` — запустить команду в фоне
• `wait` — дождаться ВСЕХ фоновых задач
• `wait $pid` — дождаться конкретной задачи
• `$!` — PID последней фоновой команды

───────────────────────────────────────
🔹 ОГРАНИЧЕННЫЙ ПАРАЛЛЕЛИЗМ (БЕЗ GNU parallel)
───────────────────────────────────────

```bash
#!/bin/bash
max_jobs=4
mkfifo "$DIR/pipe"              # Именованный канал (FIFO)
exec 3<>"$DIR/pipe"             # Открыть для чтения+записи
rm "$DIR/pipe"                  # Файл больше не нужен (дескриптор открыт)

for ((i=0; i<max_jobs; i++)); do echo >&3; done   # Начальные токены

for file in *.log; do
    read -u 3                   # Взять токен (блокирует если нет свободных!)
    {
        process_file "$file"
        echo >&3               # Вернуть токен
    } &
done
wait
exec 3>&-
```

📂 Рабочий каталог: `~/.termtrainer/scripting_013`

📋 **Попробуй**:
1. Свой дескриптор: `exec 3>/tmp/test_fd.txt; echo "hello" >&3; exec 3>&-`
2. Фоновая задача: `(sleep 1; echo done) &; wait`

