TASK
🛡️ **Страж архивов**

Архивы Университета в опасности — кто-то оставляет исполняемые файлы без присмотра, а некоторые записи устарели. Нужен скрипт-страж, который проверит всё и наведёт порядок.

📋 **Задания**:
1. Создай скрипт `guard.sh` который:
   - Проверяет каждый файл в `хранилище/` через цикл `for`
   - Если файл обычный (`-f`) и исполняемый (`-x`) — выводит `⚠ EXECUTABLE: имя_файла`
   - Если файл обычный (`-f`) и НЕ исполняемый — выводит `✓ SAFE: имя_файла`
   - В конце выводит общее количество проверенных файлов

2. Создай скрипт `audit.sh` который:
   - Читает `инвентарь.csv` построчно через `while read`
   - Для строк с "раскуплено" в 4-м поле — выводит предупреждение
   - Перенаправляет все предупреждения в файл `warnings.log` (используя `>`)
   - Перенаправляет ошибки выполнения (stderr) в `errors.log` (используя `2>`)

💡 **Коды возврата**:
• `$?` — код возврата последней команды (0 = успех)
• `exit N` — завершить скрипт с кодом N
• Используй разные коды для разных ошибок!

📂 Рабочий каталог: `~/.ninja_trainer/scripting_005`

VALIDATION
#!/bin/bash
DIR="$HOME/.ninja_trainer/scripting_005"
score=0

if [ -f "$DIR/guard.sh" ]; then
  echo "✓ guard.sh создан"
  score=$((score+1))
  output=$(bash "$DIR/guard.sh" 2>/dev/null)
  echo "$output" | grep -qi 'executable' && { echo "✓ guard.sh обнаруживает executable"; score=$((score+1)); }
fi

if [ -f "$DIR/audit.sh" ]; then
  echo "✓ audit.sh создан"
  score=$((score+1))
fi

[ $score -ge 3 ] && { echo "✓ ok: Страж архивов на посту! (баллов: $score/3)"; exit 0; }
echo "✗ Нужно больше практики (баллов: $score/3)"
exit 1

